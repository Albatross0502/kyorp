export function generateSeedProducts(categories: any[]): ProductItem[] {
  return RAW_PRODUCTS_CATALOG.map(item => {
    const skuNum = item[0];
    const skuStr = String(skuNum).padStart(3, "0");
    const name = item[1];
    const formulation = item[2];
    const type = item[3];

    const div = categories.find(d => {
      const parts = d.range.split("–");
      return skuNum >= parseInt(parts[0], 10) && skuNum <= parseInt(parts[1], 10);
    }) || categories[0];

    let priceINR = 0;
    let originalPriceINR = 0;
    let discountPct = 0;

    if (div.status === "live") {
      const spread = div.maxPrice - div.minPrice;
      const hashVal = (skuNum * 37 + name.length * 19) % 100;
      const rawPrice = div.minPrice + Math.floor((spread * (hashVal / 100)));
      priceINR = Math.round(rawPrice / 50) * 50 - 1;
      if (priceINR < div.minPrice) priceINR = div.minPrice;

      // Add realistic original price with 10-25% discount for selected flagships
      if (skuNum % 3 === 0 || skuNum === 76 || skuNum === 1) {
        discountPct = 15;
        originalPriceINR = Math.round((priceINR / (1 - discountPct / 100)) / 50) * 50;
      }
    }

    const featuredSkus = [1, 76, 84, 101, 119, 159, 188, 253];

    return {
      sku: skuStr,
      skuNum: skuNum,
      name: name,
      formulation: formulation,
      divisionId: div.id,
      divisionName: div.name,
      type: type,
      status: div.status as 'live' | 'development',
      priceINR: priceINR,
      originalPriceINR: originalPriceINR > priceINR ? originalPriceINR : undefined,
      discountPct: discountPct > 0 ? discountPct : undefined,
      inStock: true,
      featured: featuredSkus.includes(skuNum),
      tone: div.tone,
      lastUpdated: new Date().toISOString()
    };
  });
}
